// Generates 02_region_data.sql from modood/Administrative-divisions-of-China pca-code.json
// Usage: node scripts/gen-region-sql.mjs <path-to-pca-code.json>
// Run with Node.js 16+. No third-party dependencies.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const inputPath = process.argv[2] || resolve(__dirname, 'pca-code.json');
const outputPath = resolve(__dirname, '../base-service/src/main/resources/db/init/02_region_data.sql');

const raw = JSON.parse(readFileSync(inputPath, 'utf8'));

const escape = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "''");
const padCode = (code, len = 6) => code.padEnd(len, '0');

let id = 0;
const rows = [];

function walk(nodes, parentId, level) {
  nodes.forEach((node, index) => {
    id += 1;
    rows.push({ id, parentId, code: padCode(node.code), name: escape(node.name), level, sort: index + 1 });
    if (Array.isArray(node.children) && node.children.length > 0) {
      walk(node.children, id, level + 1);
    }
  });
}

walk(raw, 0, 1);

const BATCH = 500;
const header =
  '-- =====================================================\n' +
  '-- China administrative divisions (province/city/district)\n' +
  '-- Source: modood/Administrative-divisions-of-China (GB/T 2260)\n' +
  '-- Generated by scripts/gen-region-sql.mjs, DO NOT EDIT MANUALLY\n' +
  '-- =====================================================\n\n' +
  'USE `blog_base`;\n\n';

let sql = header;
for (let i = 0; i < rows.length; i += BATCH) {
  const batch = rows.slice(i, i + BATCH);
  sql += 'INSERT INTO `base_region` (`id`, `parent_id`, `code`, `name`, `level`, `sort`) VALUES\n';
  sql += batch
    .map(
      (r) =>
        `(${r.id}, ${r.parentId}, '${r.code}', '${r.name}', ${r.level}, ${r.sort})`
    )
    .join(',\n');
  sql += ';\n\n';
}

writeFileSync(outputPath, sql, 'utf8');
console.log(`rows=${rows.length}, level1=${rows.filter(r=>r.level===1).length}, level2=${rows.filter(r=>r.level===2).length}, level3=${rows.filter(r=>r.level===3).length}`);
console.log(`written: ${outputPath}`);
